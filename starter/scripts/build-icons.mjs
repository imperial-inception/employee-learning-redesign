// Generates components/ds/icon-paths.generated.tsx from the icon set in design/html/assets/shell.js,
// so the app draws exactly the same glyphs as the reference PNGs.   node scripts/build-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { MOCKUPS, STARTER } from './lib/kit.mjs';

const shell = readFileSync(resolve(MOCKUPS, 'assets', 'shell.js'), 'utf8');
const grab = name => {
  const m = shell.match(new RegExp(`const ${name} = (\\{[\\s\\S]*?\\n  \\});`));
  if (!m) throw new Error(`could not find const ${name} in shell.js`);
  return Function(`return ${m[1]}`)();
};
const P = grab('P'); // line icons (stroke 1.75, drawn by the <svg> wrapper's attributes)
const S = grab('S'); // status glyphs (filled shapes, carry their own attributes)

const camel = a => a.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
function toJsx(markup) {
  return markup
    .replace(/style="([^"]*)"/g, (_, css) => {
      const obj = css.split(';').filter(Boolean).map(d => {
        const [k, ...v] = d.split(':');
        return `${camel(k.trim())}: '${v.join(':').trim()}'`;
      }).join(', ');
      return `style={{ ${obj} }}`;
    })
    .replace(/ ([a-z]+(?:-[a-z]+)+)=/g, (_, a) => ` ${camel(a)}=`)
    .replace(/"\/>/g, '" />');
}
const block = (obj, type) => Object.entries(obj)
  .map(([k, v]) => `  '${k}': <>${toJsx(v)}</>,`).join('\n');

const out = `// GENERATED by scripts/build-icons.mjs from design/html/assets/shell.js. Do not edit by hand.
// Line icons are drawn inside <Icon>, which supplies viewBox, stroke and size; status glyphs inside <StatusIcon>.
import type { ReactElement } from 'react';

export const iconPaths = {
${block(P)}
} satisfies Record<string, ReactElement>;

export const statusPaths = {
${block(S)}
} satisfies Record<string, ReactElement>;

export type IconName = keyof typeof iconPaths;
export type StatusGlyph = keyof typeof statusPaths;
`;
writeFileSync(resolve(STARTER, 'components', 'ds', 'icon-paths.generated.tsx'), out);
console.log(`icons: ${Object.keys(P).length} line icons, ${Object.keys(S).length} status glyphs`);
