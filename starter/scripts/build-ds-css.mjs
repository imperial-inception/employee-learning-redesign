// Generates styles/ds.css and lib/tokens.generated.ts from the mockups' shared stylesheet
// (design/html/assets/styles.css), so the app and the reference PNGs can never drift apart.
//
//   node scripts/build-ds-css.mjs
//
// What it changes, and why:
// 1. Every rule is scoped to the design area with :where([data-ds]) …  :where() adds ZERO specificity, so the
//    cascade is exactly the mockups' cascade, but nothing leaks into pages that are not redesigned yet.
// 2. `body` rules move to the [data-ds] root (the design area is not the whole page in a migrating app);
//    `html` rules are dropped.
// 3. --accent* is renamed --brand* (DESIGN_SYSTEM.md §1).
// 4. Font files are served from /fonts (public/fonts).
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import postcss from 'postcss';
import { STARTER, STYLES_CSS, renameVars } from './lib/kit.mjs';

const SCOPE = ':where([data-ds])';
const src = renameVars(readFileSync(STYLES_CSS, 'utf8'));
const root = postcss.parse(src);

function scopeSelector(sel) {
  const s = sel.trim();
  if (s === ':root' || s === '[data-theme=light]') return [s];
  if (s === 'html') return [];
  if (s === 'body') return [SCOPE];
  if (s === '*') return [SCOPE, `${SCOPE} *`];
  const light = s.match(/^\[data-theme=light\]\s+(.*)$/);
  if (light) return [`[data-theme=light] ${SCOPE} ${light[1]}`];
  return [`${SCOPE} ${s}`];
}

root.walkAtRules('font-face', at => {
  at.walkDecls('src', d => { d.value = d.value.replace(/url\("fonts\//g, 'url("/fonts/'); });
});
root.walkRules(rule => {
  if (rule.parent && rule.parent.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
  const out = rule.selectors.flatMap(scopeSelector);
  if (!out.length) { rule.remove(); return; }
  rule.selectors = out;
});

const header = `/* GENERATED by scripts/build-ds-css.mjs from design/html/assets/styles.css. Do not edit by hand:
   change the mockup stylesheet (the reference PNGs come from it) and re-run \`npm run gen:css\`.
   Scope: everything below applies only inside an element with the data-ds attribute (see components/ds/DsRoot.tsx).
   Tokens (:root = dark, the default; [data-theme=light] = light) are global so portals and MUI can read them. */\n`;
writeFileSync(resolve(STARTER, 'styles', 'ds.css'), header + root.toString().replace(/^\/\*[\s\S]*?\*\/\s*/, ''));

// ---- tokens.generated.ts: the same values for JavaScript consumers (MUI theme, ECharts theme) ----
const read = sel => {
  const vals = {};
  postcss.parse(src).walkRules(r => {
    if (r.selector.trim() !== sel) return;
    r.walkDecls(d => { if (d.prop.startsWith('--')) vals[d.prop.slice(2)] = d.value.trim(); });
  });
  return vals;
};
const dark = read(':root');
const light = { ...dark, ...read('[data-theme=light]') };
const ts = `// GENERATED by scripts/build-ds-css.mjs from design/html/assets/styles.css. Do not edit by hand.
// CSS is the source of truth in the browser (var(--brand) etc.); use these values only where a library needs
// literal colours (MUI palette maths, ECharts, canvas). Keys are the CSS variable names without "--".
export const tokens = {
  dark: ${JSON.stringify(dark, null, 2).replace(/\n/g, '\n  ')},
  light: ${JSON.stringify(light, null, 2).replace(/\n/g, '\n  ')},
} as const;

export type ThemeMode = keyof typeof tokens;
export type TokenName = keyof typeof tokens.dark;
`;
writeFileSync(resolve(STARTER, 'lib', 'tokens.generated.ts'), ts);
console.log(`ds.css: ${root.nodes.length} top-level nodes; tokens: ${Object.keys(dark).length} per theme`);
